const LanguageContext = createContext(null);
const LANGUAGE_KEY = 'ag_language';

export function LanguageProvider({ children }) {
  const { user } = useAuth();
  const [language, setLanguageState] = useState(() => {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    return saved === 'bn' ? 'bn' : 'en';
  });

  useEffect(() => {
    if (user?.preferred_language === 'en' || user?.preferred_language === 'bn') {
      setLanguageState(user.preferred_language);
      localStorage.setItem(LANGUAGE_KEY, user.preferred_language);
    }
  }, [user?.id, user?.preferred_language]);

  const setLanguage = useCallback(async (nextLanguage) => {
    if (nextLanguage !== 'en' && nextLanguage !== 'bn') return;

    setLanguageState(nextLanguage);
    localStorage.setItem(LANGUAGE_KEY, nextLanguage);
    if (user) await updatePreferredLanguage(nextLanguage);
  }, [user]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => translations[language][key] ?? translations.en[key] ?? key,
  }), [language, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider.');
  return context;
}
